// api-docs renders a focused reference from the canonical generated CRD schemas.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	apiextensionsv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
	"sigs.k8s.io/yaml"
)

const outputPath = "notes/API_REFERENCE.md"

// These boundaries control presentation only. Descriptions and validation always
// come from the schema; external Kubernetes structures are not expanded here.
var standardFields = map[string]bool{
	"spec.source.job.renderer.env":       true,
	"spec.source.job.renderer.envFrom":   true,
	"spec.source.job.renderer.resources": true,
	"status.conditions":                  true,
}
var supportedFields = map[string][]string{
	"spec.source.job.volumes[]":               {"name", "configMap", "secret"},
	"spec.source.job.renderer.volumeMounts[]": {"name", "mountPath", "readOnly"},
}

func main() {
	check := flag.Bool("check", false, "compare generated reference without modifying files")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(check bool) error {
	paths, err := filepath.Glob("config/crd/bases/*.yaml")
	if err != nil {
		return err
	}
	if len(paths) == 0 {
		return fmt.Errorf("no canonical CRDs found")
	}
	crds := make([]apiextensionsv1.CustomResourceDefinition, 0, len(paths))
	for _, path := range paths {
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		var crd apiextensionsv1.CustomResourceDefinition
		if err := yaml.UnmarshalStrict(data, &crd); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		crds = append(crds, crd)
	}
	data, err := render(crds)
	if err != nil {
		return err
	}
	if check {
		current, err := os.ReadFile(outputPath)
		if err != nil {
			return err
		}
		if !bytes.Equal(data, current) {
			return fmt.Errorf("%s is stale; run make api-docs", outputPath)
		}
		return nil
	}
	return os.WriteFile(outputPath, data, 0o644)
}

func render(crds []apiextensionsv1.CustomResourceDefinition) ([]byte, error) {
	slices.SortFunc(crds, func(a, b apiextensionsv1.CustomResourceDefinition) int {
		return strings.Compare(a.Spec.Names.Kind, b.Spec.Names.Kind)
	})
	var out bytes.Buffer
	out.WriteString("# API reference\n\n<!-- Generated by tools/api-docs. Do not edit. Run make api-docs. -->\n\n")
	out.WriteString("See [API overview](API.md) for resource relationships and examples. This reference\nis generated from the CRD schemas, whose descriptions originate in\n[types.go](../api/v1alpha1/types.go). It covers ARPRT fields; Kubernetes metadata\nand the internals of standard environment, resource and Condition types are omitted.\nOnly supported Job volume and mount fields are shown.\n\n")
	for _, crd := range crds {
		for _, version := range crd.Spec.Versions {
			if version.Served {
				fmt.Fprintf(&out, "- [%s %s](#%s)\n", crd.Spec.Names.Kind, version.Name, anchor(crd.Spec.Names.Kind+" "+version.Name))
			}
		}
	}
	out.WriteByte('\n')
	out.WriteString("Required means required **when the containing object is present**. Optional\nobjects can contain required children. The admission default column contains only\nCRD defaults; controller-selected defaults and omission behavior are described in\nthe descriptions. Status is controller-managed and must not be supplied as desired\nconfiguration. Constraints summarize bounds, enum values and CEL messages; consult\nthe canonical schemas for exact regular expressions and validation rules. CEL\nmessages below describe validation failures, rather than valid configuration.\n\n")
	for _, crd := range crds {
		for _, version := range crd.Spec.Versions {
			if !version.Served {
				continue
			}
			if version.Schema == nil || version.Schema.OpenAPIV3Schema == nil {
				return nil, fmt.Errorf("missing schema for %s/%s", crd.Spec.Names.Kind, version.Name)
			}
			root := *version.Schema.OpenAPIV3Schema
			fmt.Fprintf(&out, "## %s %s\n\nAPI: `%s/%s` · Scope: `%s` · Resource: `%s`\n\n", crd.Spec.Names.Kind, version.Name, crd.Spec.Group, version.Name, crd.Spec.Scope, crd.Spec.Names.Plural)
			if root.Description != "" {
				fmt.Fprintln(&out, root.Description)
				out.WriteByte('\n')
			}
			for _, name := range []string{"spec", "status"} {
				node, exists := root.Properties[name]
				if !exists {
					return nil, fmt.Errorf("missing %s for %s", name, crd.Spec.Names.Kind)
				}
				renderObject(&out, crd.Spec.Names.Kind+" "+version.Name+" ", name, node)
			}
		}
	}
	return append(bytes.TrimRight(out.Bytes(), "\n"), '\n'), nil
}

func renderObject(out *bytes.Buffer, prefix, path string, node apiextensionsv1.JSONSchemaProps) {
	fmt.Fprintf(out, "### %s%s\n\n", prefix, path)
	if node.Description != "" {
		fmt.Fprintln(out, node.Description)
		out.WriteByte('\n')
	}
	if constraints := constraints(node); constraints != "" {
		fmt.Fprintf(out, "Constraints: %s\n\n", constraints)
	}
	if len(node.XValidations) > 0 {
		out.WriteString("Validation failure messages:\n\n")
		for _, rule := range node.XValidations {
			if rule.Message != "" {
				fmt.Fprintf(out, "- %s\n", cell(rule.Message))
			}
		}
		out.WriteByte('\n')
	}
	out.WriteString("| Field | Type | Required | Admission default | Description / constraints |\n| --- | --- | --- | --- | --- |\n")
	names := make([]string, 0, len(node.Properties))
	for name := range node.Properties {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		if allowed, ok := supportedFields[path]; ok && !slices.Contains(allowed, name) {
			continue
		}
		field := node.Properties[name]
		fieldPath := path + "." + name
		desc := field.Description
		if standardFields[fieldPath] {
			desc += " Standard Kubernetes type; nested fields are omitted."
		}
		if child, _ := childObject(field); child == nil {
			var messages []string
			for _, rule := range field.XValidations {
				if rule.Message != "" {
					messages = append(messages, rule.Message)
				}
			}
			if len(messages) > 0 {
				desc += " Validation failure messages: " + strings.Join(messages, "; ") + "."
			}
		}
		if text := constraints(field); text != "" {
			desc += " " + text
		}
		required := "No"
		if slices.Contains(node.Required, name) {
			required = "Yes"
		}
		def := "—"
		if field.Default != nil {
			def = "`" + compactJSON(field.Default.Raw) + "`"
		}
		label := "`" + name + "`"
		if child, _ := childObject(field); child != nil && !standardFields[fieldPath] {
			_, childPath := childObject(field)
			label = fmt.Sprintf("[%s](#%s)", label, anchor(prefix+fieldPath+childPath))
		}
		fmt.Fprintf(out, "| %s | %s | %s | %s | %s |\n", label, cell(typeName(field)), required, cell(def), cell(desc))
	}
	out.WriteByte('\n')
	for _, name := range names {
		if allowed, ok := supportedFields[path]; ok && !slices.Contains(allowed, name) {
			continue
		}
		fieldPath := path + "." + name
		if standardFields[fieldPath] {
			continue
		}
		if child, suffix := childObject(node.Properties[name]); child != nil {
			renderObject(out, prefix, fieldPath+suffix, *child)
		}
	}
}

func childObject(node apiextensionsv1.JSONSchemaProps) (*apiextensionsv1.JSONSchemaProps, string) {
	if len(node.Properties) > 0 {
		return &node, ""
	}
	if node.Items != nil && node.Items.Schema != nil && len(node.Items.Schema.Properties) > 0 {
		return node.Items.Schema, "[]"
	}
	return nil, ""
}

func typeName(node apiextensionsv1.JSONSchemaProps) string {
	if node.Type == "array" && node.Items != nil && node.Items.Schema != nil {
		return "array of " + typeName(*node.Items.Schema)
	}
	if node.Format != "" {
		return node.Type + " (" + node.Format + ")"
	}
	return node.Type
}

func compactJSON(raw []byte) string {
	var out bytes.Buffer
	if err := json.Compact(&out, raw); err != nil {
		return string(raw)
	}
	return out.String()
}

func constraints(node apiextensionsv1.JSONSchemaProps) string {
	var parts []string
	if len(node.Enum) > 0 {
		values := make([]string, 0, len(node.Enum))
		for _, value := range node.Enum {
			values = append(values, "`"+compactJSON(value.Raw)+"`")
		}
		parts = append(parts, "Allowed: "+strings.Join(values, ", ")+".")
	}
	if node.Minimum != nil {
		parts = append(parts, "Minimum: "+strconv.FormatFloat(*node.Minimum, 'f', -1, 64)+".")
	}
	if node.Maximum != nil {
		parts = append(parts, "Maximum: "+strconv.FormatFloat(*node.Maximum, 'f', -1, 64)+".")
	}
	if node.MinItems != nil {
		parts = append(parts, fmt.Sprintf("Minimum items: %d.", *node.MinItems))
	}
	if node.MaxItems != nil {
		parts = append(parts, fmt.Sprintf("Maximum items: %d.", *node.MaxItems))
	}
	if node.MinLength != nil {
		parts = append(parts, fmt.Sprintf("Minimum length: %d.", *node.MinLength))
	}
	if node.MaxLength != nil {
		parts = append(parts, fmt.Sprintf("Maximum length: %d.", *node.MaxLength))
	}
	if node.Pattern != "" {
		parts = append(parts, "Format is validated by the schema.")
	}
	if node.Items != nil && node.Items.Schema != nil {
		if itemConstraints := constraints(*node.Items.Schema); itemConstraints != "" {
			parts = append(parts, "Each item: "+itemConstraints)
		}
	}
	return strings.Join(parts, " ")
}

func cell(value string) string {
	value = strings.Join(strings.Fields(value), " ")
	value = strings.ReplaceAll(value, "&", "&amp;")
	value = strings.ReplaceAll(value, "<", "&lt;")
	value = strings.ReplaceAll(value, ">", "&gt;")
	return strings.ReplaceAll(value, "|", "&#124;")
}

func anchor(path string) string {
	// Match GitHub and tools/check-docs.py heading slugs for JSON field paths.
	return strings.ToLower(strings.NewReplacer(" ", "-", ".", "", "[", "", "]", "").Replace(path))
}
